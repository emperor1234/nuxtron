import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

const { apiGet, apiSend, resolveSessionTenant } = vi.hoisted(() => ({
  apiGet: vi.fn(),
  apiSend: vi.fn(),
  resolveSessionTenant: vi.fn(() => 'workspace-test'),
}));

vi.mock('@/app/lib/api-client', () => ({ resolveSessionTenant }));
vi.mock('@/app/lib/platform-api', () => ({ apiGet, apiSend }));

import ContentGenerationPage from './page';

afterEach(() => cleanup());

beforeEach(() => {
  apiGet.mockReset();
  apiSend.mockReset();
  resolveSessionTenant.mockReturnValue('workspace-test');
  apiGet.mockImplementation((path: string) => Promise.resolve(
    path === '/content/library'
      ? { status: 'ok', count: 0, items: [] }
      : { status: 'ok', items: [], retention: { terminal_seconds: 3600 } },
  ));
});

function completeBrief() {
  fireEvent.change(screen.getByLabelText('Topic'), { target: { value: 'Launch a new analytics report' } });
  fireEvent.change(screen.getByLabelText('Audience'), { target: { value: 'Product marketing teams' } });
  fireEvent.change(screen.getByLabelText('Channel'), { target: { value: 'linkedin' } });
  fireEvent.change(screen.getByLabelText('Tone'), { target: { value: 'professional' } });
}

describe('AI Content Generation page', () => {
  it('starts with a blank, labeled brief, one primary action, and opt-in queue refresh', async () => {
    render(<ContentGenerationPage />);

    expect((screen.getByLabelText('Topic') as HTMLInputElement).value).toBe('');
    expect((screen.getByLabelText('Audience') as HTMLInputElement).value).toBe('');
    expect((screen.getByLabelText('Channel') as HTMLSelectElement).value).toBe('');
    expect((screen.getByLabelText('Tone') as HTMLSelectElement).value).toBe('');
    expect(screen.getAllByRole('button', { name: 'Generate content' })).toHaveLength(1);
    expect(screen.getByText(/Background refresh: Off/)).toBeTruthy();

    fireEvent.click(screen.getByText('Filters and background refresh'));
    expect((screen.getByLabelText('Background refresh interval') as HTMLSelectElement).value).toBe('30');
    await waitFor(() => expect(apiGet).toHaveBeenCalledWith('/content/library', 'workspace-test'));
  });

  it('submits the actual brief to the session workspace and labels template fallback as not AI-generated', async () => {
    apiSend.mockResolvedValue({
      status: 'ok',
      generation_id: 'cg-test',
      ai_status: 'fallback',
      headline: 'A template headline',
      body: 'A template body based on the brief.',
      provider_used: 'unconfigured',
      model_used: '',
      generated_assets: {
        image: { generation_status: 'fallback', download_url: '/generated/fallback.png', file_name: 'fallback.png' },
      },
    });
    render(<ContentGenerationPage />);
    completeBrief();
    fireEvent.click(screen.getByRole('button', { name: 'Generate content' }));

    expect(await screen.findByText(/Template fallback — this copy was not generated by an AI provider/i)).toBeTruthy();
    expect(screen.getByText('A template body based on the brief.')).toBeTruthy();
    expect(screen.getByText('image: fallback')).toBeTruthy();
    expect(screen.queryByText('Provider: unconfigured')).toBeNull();
    expect(apiSend).toHaveBeenCalledWith(
      '/content/generate',
      'POST',
      { topic: 'Launch a new analytics report', audience: 'Product marketing teams', channel: 'linkedin', tone: 'professional', include_seo: true },
      'workspace-test',
    );
  });

  it('loads a saved generation through the real item envelope instead of exposing JSON as a download', async () => {
    apiGet.mockImplementation((path: string) => Promise.resolve(
      path === '/content/library'
        ? { status: 'ok', count: 1, items: [{ generation_id: 'cg-saved', topic: 'Saved topic', channel: 'blog', headline: 'Saved headline', created_at: '2026-10-12T00:00:00Z' }] }
        : path === '/content/library/cg-saved'
          ? { status: 'ok', item: { response: { status: 'ok', generation_id: 'cg-saved', ai_status: 'generated', headline: 'Saved headline', body: 'Saved body loaded from the actual item endpoint.' } } }
          : { status: 'ok', items: [], retention: { terminal_seconds: 3600 } },
    ));
    render(<ContentGenerationPage />);

    fireEvent.click(await screen.findByRole('button', { name: 'View saved content' }));
    expect(await screen.findByText('Saved body loaded from the actual item endpoint.')).toBeTruthy();
    expect(apiGet).toHaveBeenCalledWith('/content/library/cg-saved', 'workspace-test');
  });

  it('does not issue customer API reads or enable generation without a workspace', async () => {
    resolveSessionTenant.mockReturnValue('');
    render(<ContentGenerationPage />);

    expect(await screen.findByText('Sign in to a workspace to load saved content.')).toBeTruthy();
    expect(apiGet).not.toHaveBeenCalled();
    expect((screen.getByRole('button', { name: 'Generate content' }) as HTMLButtonElement).disabled).toBe(true);
  });
});
